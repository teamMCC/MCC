    /**
     * 좌표가 속한 지역. 국내가 아니거나(에뮬레이터 기본 위치는 미국) 판정이 어려우면 null.
     */
    fun classify(lat: Double, lng: Double): Region? {
        val cosLat = cos(Math.toRadians(lat))
        var best: Anchor? = null
        var bestD2 = Double.MAX_VALUE
        for (a in ANCHORS) {
            val dy = lat - a.lat
            val dx = (lng - a.lng) * cosLat
            val d2 = dx * dx + dy * dy
            if (d2 < bestD2) {
                bestD2 = d2
                best = a
            }
        }
        if (best == null || sqrt(bestD2) > MAX_DISTANCE_DEG) return null
        return best.region
    }

